#!/bin/sh
# Скрипт резервного копирования базы данных интернет-магазина
# Использует pg_dump. Параметры подключения берутся из переменных окружения.
# Не содержит реальных учётных данных.

# ---------------------------------------------------------------------------
# Настройки (по умолчанию берутся из переменных окружения)
# ---------------------------------------------------------------------------
PGHOST="${PGHOST:-localhost}"
PGPORT="${PGPORT:-5432}"
PGUSER="${PGUSER:-postgres}"
PGDATABASE="${PGDATABASE:-shopdb}"
PGPASSWORD="${PGPASSWORD:-}"

BACKUP_DIR="${BACKUP_DIR:-./backups}"
TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
BACKUP_FILE="${BACKUP_DIR}/shopdb_backup_${TIMESTAMP}.sql"

# ---------------------------------------------------------------------------
# Проверка наличия pg_dump
# ---------------------------------------------------------------------------
if ! command -v pg_dump >/dev/null 2>&1; then
    echo "Ошибка: утилита pg_dump не найдена. Установите PostgreSQL client."
    exit 1
fi

# ---------------------------------------------------------------------------
# Создание директории для бэкапов
# ---------------------------------------------------------------------------
mkdir -p "${BACKUP_DIR}"

# ---------------------------------------------------------------------------
# Резервное копирование
# ---------------------------------------------------------------------------
echo "Начало резервного копирования базы данных ${PGDATABASE}..."
echo "Хост: ${PGHOST}:${PGPORT}, пользователь: ${PGUSER}"
echo "Файл бэкапа: ${BACKUP_FILE}"

export PGPASSWORD

if pg_dump -h "${PGHOST}" -p "${PGPORT}" -U "${PGUSER}" -d "${PGDATABASE}" > "${BACKUP_FILE}" 2>/tmp/pg_dump_error.log; then
    echo "Резервное копирование завершено успешно: ${BACKUP_FILE}"
    rm -f /tmp/pg_dump_error.log
else
    echo "Ошибка при создании резервной копии!"
    cat /tmp/pg_dump_error.log
    rm -f /tmp/pg_dump_error.log
    exit 1
fi

# ---------------------------------------------------------------------------
# Опционально: удаление бэкапов старше 30 дней
# ---------------------------------------------------------------------------
# find "${BACKUP_DIR}" -name "shopdb_backup_*.sql" -mtime +30 -delete

exit 0