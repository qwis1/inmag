#!/bin/sh
# Скрипт восстановления базы данных интернет-магазина из резервной копии
# Использует psql. Параметры подключения берутся из переменных окружения.
# Не содержит реальных учётных данных.

# ---------------------------------------------------------------------------
# Настройки (по умолчанию берутся из переменных окружения)
# ---------------------------------------------------------------------------
PGHOST="${PGHOST:-localhost}"
PGPORT="${PGPORT:-5432}"
PGUSER="${PGUSER:-postgres}"
PGDATABASE="${PGDATABASE:-shopdb}"
PGPASSWORD="${PGPASSWORD:-}"

# Путь к файлу бэкапа передаётся первым аргументом
BACKUP_FILE="${1}"

# ---------------------------------------------------------------------------
# Проверка аргументов
# ---------------------------------------------------------------------------
if [ -z "${BACKUP_FILE}" ]; then
    echo "Использование: $0 <путь_к_файлу_бэкапа.sql>"
    echo "Пример: $0 ./backups/shopdb_backup_20261009_120000.sql"
    exit 1
fi

if [ ! -f "${BACKUP_FILE}" ]; then
    echo "Ошибка: файл бэкапа не найден: ${BACKUP_FILE}"
    exit 1
fi

# ---------------------------------------------------------------------------
# Проверка наличия psql
# ---------------------------------------------------------------------------
if ! command -v psql >/dev/null 2>&1; then
    echo "Ошибка: утилита psql не найдена. Установите PostgreSQL client."
    exit 1
fi

# ---------------------------------------------------------------------------
# Восстановление
# ---------------------------------------------------------------------------
echo "Начало восстановления базы данных ${PGDATABASE} из файла: ${BACKUP_FILE}"
echo "Хост: ${PGHOST}:${PGPORT}, пользователь: ${PGUSER}"

export PGPASSWORD

if psql -h "${PGHOST}" -p "${PGPORT}" -U "${PGUSER}" -d "${PGDATABASE}" -f "${BACKUP_FILE}" 2>/tmp/psql_restore_error.log; then
    echo "Восстановление завершено успешно."
    rm -f /tmp/psql_restore_error.log
else
    echo "Ошибка при восстановлении базы данных!"
    cat /tmp/psql_restore_error.log
    rm -f /tmp/psql_restore_error.log
    exit 1
fi

exit 0